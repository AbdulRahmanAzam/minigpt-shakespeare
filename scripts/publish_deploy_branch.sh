#!/usr/bin/env bash
# Refresh the `deploy` branch: only the files the NumPy server image needs, so hosts that scan the repository
# for ML packages (SnapDeploy refuses PyTorch on CPU containers) see no torch dependency or import.
#
#   bash scripts/publish_deploy_branch.sh          # commit + push origin/deploy from the current HEAD
set -euo pipefail

FILES=(Dockerfile .dockerignore requirements-deploy.txt src/__init__.py src/api.py src/numpy_gpt.py src/tokenizer.py)
SRC_SHA=$(git rev-parse --short HEAD)
TMP=$(mktemp -d)
trap 'git worktree remove --force "$TMP" >/dev/null 2>&1 || true' EXIT

git fetch -q origin deploy 2>/dev/null || true
if git rev-parse -q --verify origin/deploy >/dev/null; then
  git worktree add -q -B deploy "$TMP" origin/deploy
else
  git worktree add -q --detach "$TMP"
  git -C "$TMP" checkout -q --orphan deploy
fi
git -C "$TMP" rm -rqf --ignore-unmatch . >/dev/null
for f in "${FILES[@]}"; do
  mkdir -p "$TMP/$(dirname "$f")"
  git show "HEAD:$f" > "$TMP/$f"
done
cat > "$TMP/README.md" <<EOF
# MiniGPT Shakespeare — serving branch

Generated by \`scripts/publish_deploy_branch.sh\` from \`main\` @ $SRC_SHA. Do not edit here; see the \`main\` branch.
EOF
git -C "$TMP" add -A
if git -C "$TMP" diff --cached --quiet; then
  echo "deploy branch already up to date"
else
  git -C "$TMP" commit -q -m "Serving files from main @ $SRC_SHA"
  git -C "$TMP" push -q origin deploy
  echo "pushed deploy branch (from main @ $SRC_SHA)"
fi
